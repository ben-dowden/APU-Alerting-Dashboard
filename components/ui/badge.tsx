import * as React from "react";
import { cva, type VariantProps } from "class-variance-authority";

import { cn } from "@/lib/utils/cn";

const badgeVariants = cva(
  "inline-flex items-center rounded-md border px-2 py-0.5 text-xs font-semibold transition-colors",
  {
    variants: {
      variant: {
        default: "border-transparent bg-virgin-purple text-white",
        purple: "border-transparent bg-virgin-purple text-white",
        red: "border-transparent bg-virgin-red text-white",
        neutral: "border-neutral-300 bg-white text-neutral-800",
        secondary: "border-transparent bg-neutral-100 text-neutral-800",
        outline: "border-neutral-300 text-neutral-800",
      },
    },
    defaultVariants: {
      variant: "default",
    },
  },
);

export interface BadgeProps
  extends React.HTMLAttributes<HTMLDivElement>,
    VariantProps<typeof badgeVariants> {}

function Badge({ className, variant, ...props }: BadgeProps) {
  return <div className={cn(badgeVariants({ variant, className }))} {...props} />;
}

export { Badge, badgeVariants };
